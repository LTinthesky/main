run <- function(script, wd) {
  old <- setwd(wd); on.exit(setwd(old))
  log <- paste0(basename(script),".log")
  status <- system2(file.path(R.home("bin"),"Rscript"),script,stdout=log,stderr=log)
  if (status!=0) stop(script," failed; see ",file.path(wd,log))
  cat("PASS",script,"\n")
}
